def tell_joke():
    """
    This function tells a classic programming joke.
    """
    question = "Why do programmers prefer dark mode?"
    answer = "Because light attracts bugs!"

    print(question)
    print(answer)

def tell_another_joke():
    """
    This function tells another classic programming joke.
    """
    question = "Why don't programmers like nature?"
    answer = "It has too many bugs."

    print(question)
    print(answer)

if __name__ == "__main__":
    tell_joke()
    print("\\n---And another one!---\\n")
    tell_another_joke()
